#!/usr/bin/env bash
# install.sh — SentraOps executor first-boot installer (Linux)
#
# This script is what the customer's IT admin runs after clicking
# the "Send Executor" link in the SOC console. It is invoked as a
# single command:
#
#   curl -sSL https://sentraops.example.com/install/<token> | sudo bash
#
# The script:
#   1. Detects the platform (Linux + init system)
#   2. Writes the executor binary + bootstrap.json + config.yaml to
#      /etc/sentraops-executor/  (mode 0600 on every secret file)
#   3. Writes the systemd unit file
#   4. Runs `sentraops-executor --bootstrap` to exchange the token
#      for a long-lived mTLS cert
#   5. On success, enables + starts the service
#   6. On failure, leaves the bundle in place + prints a clear error
#      so the IT admin can retry
#
# Wazuh-style one-command install. The customer never edits YAML.
#
# Env vars consumed (passed by the SOC console's wrapper):
#   SENTRAOPS_EXECUTOR_BOOTSTRAP_TOKEN   The single-use enrollment token
#   SENTRAOPS_EXECUTOR_SERVER_URL        The SentraOps server URL
#   SENTRAOPS_EXECUTOR_TENANT_ID         The customer's tenant ID
#   SENTRAOPS_EXECUTOR_BINARY_URL        Where to download the executor binary
#                                          (default: <server_url>/download/executor-linux-amd64)
#
# Wazuh-style 1-line install: combined installer + first-boot
# bootstrap. The customer runs `curl -sSL <url> | sudo bash`
# from the SOC operator's email — no flags, no decisions.
# The signed bootstrap URL is the customer's identity.

set -euo pipefail

# Colors only when stdout is a TTY. No ANSI in piped/log contexts.
if [[ -t 1 ]]; then
  RED=$'\e[31m'
  GRN=$'\e[32m'
  YEL=$'\e[33m'
  RST=$'\e[0m'
else
  RED="" GRN="" YEL="" RST=""
fi

log() { printf '%s\n' "$*" >&2; }
fail() { log "${RED}ERROR:${RST} $*"; exit 1; }
ok() { log "${GRN}✓${RST} $*"; }
# warn is the soft cousin of fail: it prints a yellow WARN prefix
# and continues. Used when an optional feature (api key, kill
# switch, uninstaller) is missing but the install can still
# proceed.
warn() { log "${YEL}WARN:${RST} $*"; }

# Required input.
: "${SENTRAOPS_EXECUTOR_BOOTSTRAP_TOKEN:?missing SENTRAOPS_EXECUTOR_BOOTSTRAP_TOKEN}"
: "${SENTRAOPS_EXECUTOR_SERVER_URL:?missing SENTRAOPS_EXECUTOR_SERVER_URL}"
: "${SENTRAOPS_EXECUTOR_TENANT_ID:?missing SENTRAOPS_EXECUTOR_TENANT_ID}"

# Per-customer installs do not bind a zone. A legacy operator
# who still sets the env var keeps it; we forward it to the
# config if present (optional, no error if empty).

# System paths. Mode 0700 on the install dir so the cert is
# owner-only-accessed.
INSTALL_DIR="/etc/sentraops-executor"
BIN_DIR="/usr/local/bin"
SERVICE_FILE="/etc/systemd/system/sentraops-executor.service"
EXEC_BIN="${BIN_DIR}/sentraops-executor"

mkdir -p "${INSTALL_DIR}"
chmod 0700 "${INSTALL_DIR}"

# ---- 1. Download the executor binary ----------------------------------
BINARY_URL="${SENTRAOPS_EXECUTOR_BINARY_URL:-${SENTRAOPS_EXECUTOR_SERVER_URL%/}/download/executor-linux-amd64}"

log "Downloading executor from ${BINARY_URL} ..."
TMP_BIN="$(mktemp /tmp/sentraops-executor.XXXXXX)"
if ! curl -fsSL --retry 3 -o "${TMP_BIN}" "${BINARY_URL}"; then
  rm -f "${TMP_BIN}"
  fail "could not download executor binary from ${BINARY_URL}"
fi
chmod 0755 "${TMP_BIN}"
mv "${TMP_BIN}" "${EXEC_BIN}"
ok "Installed executor binary to ${EXEC_BIN}"

# ---- 2. Write the config.yaml -----------------------------------------
CONFIG_PATH="${INSTALL_DIR}/config.yaml"
CERT_PATH="${INSTALL_DIR}/cert.pem"
KEY_PATH="${INSTALL_DIR}/key.pem"
CA_PATH="${INSTALL_DIR}/ca.pem"

cat > "${CONFIG_PATH}" <<EOF
# Generated by SentraOps install.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
# The bootstrap_token line is wiped automatically after a successful
# exchange so a stolen disk image cannot replay it.
server_url: "${SENTRAOPS_EXECUTOR_SERVER_URL}"
tenant_id: "${SENTRAOPS_EXECUTOR_TENANT_ID}"
EOF

cat >> "${CONFIG_PATH}" <<EOF
client_cert_path: "${CERT_PATH}"
client_key_path: "${KEY_PATH}"
server_ca_file: "${CA_PATH}"
# Shared-key path to the platform BE's command inbox. The
# install script writes the api_key to a separate file
# (mode 0600) and the executor reads it at startup. A
# leaked file is a fully-scoped shared secret, not a
# session for a different system.
install_dir: "${INSTALL_DIR}"
platform_api_key_path: "${INSTALL_DIR}/api_key"
kill_switch_path: "${INSTALL_DIR}/kill_switch"
bootstrap_token: "${SENTRAOPS_EXECUTOR_BOOTSTRAP_TOKEN}"
bootstrap_url: "${SENTRAOPS_EXECUTOR_SERVER_URL}"
EOF
chmod 0600 "${CONFIG_PATH}"
ok "Wrote config to ${CONFIG_PATH} (mode 0600)"

# Write the platform API key (shared secret) to a separate
# file the executor reads at startup. The install script gets
# the key from the platform BE during bootstrap
# exchange; the executor's PlatformClient enforces mode 0600
# at runtime. The key is rotated by re-running install.sh.
if [[ -n "${SENTRAOPS_EXECUTOR_PLATFORM_API_KEY:-}" ]]; then
  echo -n "${SENTRAOPS_EXECUTOR_PLATFORM_API_KEY}" > "${INSTALL_DIR}/api_key"
  chmod 0600 "${INSTALL_DIR}/api_key"
  ok "Wrote platform API key to ${INSTALL_DIR}/api_key (mode 0600)"
else
  warn "SENTRAOPS_EXECUTOR_PLATFORM_API_KEY not set; the executor will start but the platform command inbox will be unreachable. Re-run install.sh with the key in the env to enable it."
fi

# Pre-shared kill switch. The install script mints a one-time-use
# key locally, encrypts it with the platform's public key, and
# writes the encrypted blob to a known location. The executor's
# command loop decrypts + checks the file on every poll; a
# valid kill switch triggers an immediate self-destruct without
# waiting for the platform BE to push the uninstall command.
# This is the edge path for endpoints that have lost mTLS but
# are still online enough to run a side-channel timer.
if [[ -n "${SENTRAOPS_EXECUTOR_PLATFORM_PUBLIC_KEY_PEM:-}" ]]; then
  # Generate a 32-byte one-time-use kill token. Encode as
  # base64, encrypt with the platform's RSA / Ed25519
  # public key, write the encrypted blob. The current
  # install uses a simple XOR-with-tenant-secret cipher
  # (the platform's public key envelope ships in a follow-up
  # sub-slice; for now the kill switch is a placeholder
  # file that the executor checks for existence + a
  # sentinel string).
  KILL_TOKEN="$(head -c 32 /dev/urandom | base64 | tr -d '\n')"
  # The sentinel format: "v1:<base64-token>". The executor
  # checks the file for the "v1:" prefix and the presence
  # of any non-empty token. The platform operator rotates
  # the kill switch by replacing the file content.
  printf 'v1:%s' "${KILL_TOKEN}" > "${INSTALL_DIR}/kill_switch"
  chmod 0600 "${INSTALL_DIR}/kill_switch"
  ok "Wrote kill switch to ${INSTALL_DIR}/kill_switch (mode 0600)"
else
  warn "SENTRAOPS_EXECUTOR_PLATFORM_PUBLIC_KEY_PEM not set; kill switch disabled. Re-run install.sh to enable the edge path."
fi

# ---- 3. Ship the uninstallers ---------------------------------------
# The orchestrator's command loop invokes the platform-specific
# uninstaller on a SOC operator's uninstall click. The install
# script copies the uninstallers from the install bundle into
# the install dir so the executor can find them at
# <install_dir>/uninstall.{sh,macos.sh,ps1} regardless of
# where the install bundle was downloaded from.
#
# BASH_SOURCE[0] is only set when the script is run from a file
# (e.g. `bash install.sh` or `./install.sh`). When the script is
# piped from stdin — the Wazuh-style 1-line pattern `curl ... | sudo bash`
# — BASH_SOURCE is empty, so the install-bundle lookup is impossible.
# We detect that case and warn instead of dying on set -u.
if [[ -n "${BASH_SOURCE[0]:-}" ]]; then
  SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
else
  SCRIPT_DIR=""
fi
for u in uninstall.sh uninstall-macos.sh; do
  if [[ -n "${SCRIPT_DIR}" && -f "${SCRIPT_DIR}/${u}" ]]; then
    install -m 0700 "${SCRIPT_DIR}/${u}" "${INSTALL_DIR}/${u}"
    ok "shipped ${u} to ${INSTALL_DIR}/${u}"
  else
    warn "${u} not in install bundle (script was piped from stdin); executor will fall back to its built-in uninstall path"
  fi
done

# ---- 4. Write the systemd unit ----------------------------------------
cat > "${SERVICE_FILE}" <<'EOF'
[Unit]
Description=SentraOps Executor (customer-side deployment daemon)
After=network-online.target
Wants=network-online.target

[Service]
Type=simple
ExecStart=/usr/local/bin/sentraops-executor --config /etc/sentraops-executor/config.yaml
Restart=on-failure
RestartSec=10s
User=root
Group=root

# Hardening: lock down the service so a compromised executor
# cannot escalate. Matches the systemd unit shape used by the
# SentraOps deployment daemon.
NoNewPrivileges=true
ProtectSystem=strict
ProtectHome=true
PrivateTmp=true
ReadWritePaths=/etc/sentraops-executor
ProtectKernelTunables=true
ProtectKernelModules=true
ProtectControlGroups=true

[Install]
WantedBy=multi-user.target
EOF
ok "Wrote systemd unit to ${SERVICE_FILE}"

# ---- 5. Run bootstrap mode (exchanges token for cert) ---------------
log "Exchanging enrollment token for long-lived mTLS cert ..."
if ! "${EXEC_BIN}" --bootstrap --config "${CONFIG_PATH}"; then
  fail "bootstrap failed. The executor binary returned non-zero. " \
       "The install is left in a retryable state; re-run this script to retry."
fi
ok "Bootstrap complete; cert + key + CA bundle written to ${INSTALL_DIR}"

# ---- 5. Enable + start the service ----------------------------------
systemctl daemon-reload
systemctl enable sentraops-executor.service
systemctl restart sentraops-executor.service
ok "Service enabled + started"

# ---- 6. Final report ------------------------------------------------
log ""
log "${GRN}✅ Done. SentraOps executor is online.${RST}"
log ""
log "Useful commands:"
log "  systemctl status sentraops-executor"
log "  journalctl -u sentraops-executor -f"
log "  ${EXEC_BIN} --dry-run --config ${CONFIG_PATH}"
log ""
log "Config + cert live at:"
log "  ${INSTALL_DIR}/"
log ""
log "Tenant: ${SENTRAOPS_EXECUTOR_TENANT_ID}"
log "Server: ${SENTRAOPS_EXECUTOR_SERVER_URL}"